    private void jButtoncancelarcitaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtoncancelarcitaActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una cita.");
            return;
        }

        String id = jTable1.getValueAt(fila, 0).toString();

        int confirmar = JOptionPane.showConfirmDialog(this, "¿Deseas cancelar esta cita?", "Confirmar cancelación", JOptionPane.YES_NO_OPTION);

        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        CancelAppointment cancelar = new CancelAppointment();

        if (cancelar.cancelAppointment(id)) {
            JOptionPane.showMessageDialog(this, "Cita cancelada correctamente.");
            cargarCitas();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo cancelar la cita.");
        }
    }//GEN-LAST:event_jButtoncancelarcitaActionPerformed

    private void jButtonModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonModificarActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una cita de la tabla.");
            return;
        }

        String id = jTable1.getValueAt(fila, 0).toString();
        String motivoActual = jTable1.getValueAt(fila, 5).toString();
        String observacionActual = jTable1.getValueAt(fila, 7).toString();

        String nuevoMotivo = JOptionPane.showInputDialog(this, "Nuevo motivo:", motivoActual);

        if (nuevoMotivo == null || nuevoMotivo.trim().isEmpty()) {
            return;
        }

        String nuevasObservaciones = JOptionPane.showInputDialog(this, "Nuevas observaciones:", observacionActual);

        if (nuevasObservaciones == null) {
            return;
        }

        UpdateAppointment update = new UpdateAppointment();
        boolean actualizado = update.updateAppointment(id, nuevoMotivo.trim(), nuevasObservaciones.trim());

        if (actualizado) {
            JOptionPane.showMessageDialog(this, "Cita modificada correctamente.");
            cargarCitas();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo modificar la cita.");
        }
    }//GEN-LAST:event_jButtonModificarActionPerformed

