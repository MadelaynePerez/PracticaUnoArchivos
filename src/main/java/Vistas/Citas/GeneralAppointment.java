    private String obtenerUuidSeleccionado() {

        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione una cita de la tabla."
            );
            return null;
        }

        return jTable1.getValueAt(fila, 0).toString();
    }

    private void cargarTabla(ArrayList<Appointment> appointments) {

        DefaultTableModel model = new DefaultTableModel();

        model.addColumn("UUID");
        model.addColumn("Paciente");
        model.addColumn("Médico");
        model.addColumn("Fecha");
        model.addColumn("Hora");
        model.addColumn("Motivo");
        model.addColumn("Estado");
        model.addColumn("Observación");

        for (Appointment appointment : appointments) {

            model.addRow(new Object[]{
                appointment.getId(),
                appointment.getInePaciente(),
                appointment.getUUIdDoctor(),
                appointment.getDate(),
                appointment.getStartHour(),
                appointment.getReason(),
                appointment.isStatus(),
                appointment.getObservation()
            });
        }

        jTable1.setModel(model);
    }

    private void mostrarCitas(ArrayList<Appointment> citas) {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        for (Appointment cita : citas) {
            modelo.addRow(new Object[]{
                cita.getId(),
                cita.getInePaciente(),
                cita.getUUIdDoctor(),
                cita.getDate(),
                cita.getStartHour(),
                cita.getReason(),
                cita.isStatus(),
                cita.getObservation()
            });
        }
    }

    private void cargarCitas() {
        ListAppointment lista
                = new ListAppointment();

        mostrarCitas(lista.listAppointments());
    }

