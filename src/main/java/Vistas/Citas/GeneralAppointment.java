    private void ButtonCitaPacienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtonCitaPacienteActionPerformed
        // TODO add your handling code here:
        String texto = JOptionPane.showInputDialog(this, "Ingrese el INE del paciente:");

        if (texto == null || texto.trim().isEmpty()) {
            return;
        }

        try {
            int ine = Integer.parseInt(texto.trim());
            ArrayList<Appointment> resultado = new ArrayList<>();
            ListAppointment lista = new ListAppointment();

            for (Appointment cita : lista.listAppointments()) {
                if (cita.getInePaciente() == ine) {
                    resultado.add(cita);
                }
            }

            mostrarCitas(resultado);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El INE debe ser numérico.");
        }
    }//GEN-LAST:event_ButtonCitaPacienteActionPerformed

    private void jButtonCitaMedicoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCitaMedicoActionPerformed
        // TODO add your handling code here:
        String uuid = JOptionPane.showInputDialog(this, "Ingrese el UUID del médico:");

        if (uuid == null || uuid.trim().isEmpty()) {
            return;
        }

        ArrayList<Appointment> resultado = new ArrayList<>();
        ListAppointment lista = new ListAppointment();

        for (Appointment cita : lista.listAppointments()) {
            if (cita.getUUIdDoctor().equalsIgnoreCase(uuid.trim())) {
                resultado.add(cita);
            }
        }

        mostrarCitas(resultado);
    }//GEN-LAST:event_jButtonCitaMedicoActionPerformed

    private void jButtonCitaFechaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCitaFechaActionPerformed
        // TODO add your handling code here:
        String texto = JOptionPane.showInputDialog(this, "Ingrese la fecha (YYYY-MM-DD):");

        if (texto == null || texto.trim().isEmpty()) {
            return;
        }

        try {
            java.time.LocalDate fecha = java.time.LocalDate.parse(texto.trim());
            ArrayList<Appointment> resultado = new ArrayList<>();
            ListAppointment lista = new ListAppointment();

            for (Appointment cita : lista.listAppointments()) {
                if (cita.getDate().equals(fecha)) {
                    resultado.add(cita);
                }
            }

            mostrarCitas(resultado);

        } catch (java.time.format.DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "La fecha debe tener formato YYYY-MM-DD.");
        }
    }//GEN-LAST:event_jButtonCitaFechaActionPerformed

    private void jButtonCitaEstadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCitaEstadoActionPerformed
        // TODO add your handling code here:
        String[] estados = {"programada", "atendida", "cancelada"};

        String estado = (String) JOptionPane.showInputDialog(this, "Seleccione el estado:", "Buscar por estado", JOptionPane.QUESTION_MESSAGE, null, estados, estados[0]);

        if (estado == null) {
            return;
        }

        ArrayList<Appointment> resultado = new ArrayList<>();
        ListAppointment lista = new ListAppointment();

        for (Appointment cita : lista.listAppointments()) {
            if (cita.isStatus().equalsIgnoreCase(estado)) {
                resultado.add(cita);
            }
        }

        mostrarCitas(resultado);
    }//GEN-LAST:event_jButtonCitaEstadoActionPerformed

