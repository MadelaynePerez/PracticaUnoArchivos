    private void jButtonBuscarUIIDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonBuscarUIIDActionPerformed
        // TODO add your handling code here:
        String uuid = txtuuid.getText().trim();

        if (uuid.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe el UUID de la cita.");
            return;
        }

        SearchAppointment search = new SearchAppointment();
        Appointment cita = search.searchById(uuid);

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        if (cita != null) {
            modelo.addRow(new Object[]{
                cita.getId(),
                cita.getInePaciente(),
                cita.getUUIdDoctor(),
                cita.getDate(),
                cita.getStartHour(),
                cita.getReason(),
                cita.isStatus(),
                cita.getObservation()
            });
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró la cita.");
        }
    }//GEN-LAST:event_jButtonBuscarUIIDActionPerformed

