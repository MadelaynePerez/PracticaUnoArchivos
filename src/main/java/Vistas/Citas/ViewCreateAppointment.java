    private void cargarMedicos() {
        try {
            ListDoctors listaDoctores = new ListDoctors();
            doctoresDisponibles = listaDoctores.listDoctors();

            comboMedicos.removeAllItems();

            for (Doctor doctor : doctoresDisponibles) {
                if (doctor.isActive()) {
                    comboMedicos.addItem(doctor.getFullName() + " - " + doctor.getSpecialty());
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar médicos: " + e.getMessage());
        }
    }

