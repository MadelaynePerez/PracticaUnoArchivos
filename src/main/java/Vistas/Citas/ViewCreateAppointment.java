    private void ButonCrrearCitaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButonCrrearCitaActionPerformed
        // TODO add your handling code here:
        try {
            String id = txtUUIDcita.getText().trim();
            String ineTexto = txtInePaci.getText().trim();
            String fechaTexto = txtFecha.getText().trim();
            String horaTexto = txtHora.getText().trim();
            String motivo = txtmotivo.getText().trim();
            String observaciones = txtObservaciones.getText().trim();

            int indiceMedico = comboMedicos.getSelectedIndex();

            if (indiceMedico == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un médico.");
                return;
            }

            Doctor doctorSeleccionado = doctoresDisponibles.get(indiceMedico);
            String uuidMedico = doctorSeleccionado.getId();

            if (ineTexto.isEmpty() || fechaTexto.isEmpty() || horaTexto.isEmpty() || motivo.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete todos los campos obligatorios.");
                return;
            }

            int inePaciente = Integer.parseInt(ineTexto);
            LocalDate fecha = LocalDate.parse(fechaTexto);
            LocalTime hora = LocalTime.parse(horaTexto);

            ListPatients listaPacientes = new ListPatients();
            ArrayList<Patient> pacientes = listaPacientes.listPatients();
            boolean pacienteExiste = false;

            for (Patient paciente : pacientes) {
                if (paciente.getIne() == inePaciente) {
                    pacienteExiste = true;
                    break;
                }
            }

            if (!pacienteExiste) {
                JOptionPane.showMessageDialog(this, "No existe ningún paciente con el INE: " + inePaciente);
                return;
            }

            ListAppointment listaCitas = new ListAppointment();
            ArrayList<Appointment> citas = listaCitas.listAppointments();

            for (Appointment cita : citas) {
                if (cita.getUUIdDoctor().equals(uuidMedico) && cita.getDate().equals(fecha) && cita.getStartHour().equals(hora) && !cita.isDeleted() && !cita.isStatus().equalsIgnoreCase("cancelada")) {
                    JOptionPane.showMessageDialog(this, "El médico ya tiene una cita programada para esa fecha y hora.");
                    return;
                }
            }

            Appointment appointment = new Appointment();
            appointment.setId(id);
            appointment.setInePaciente(inePaciente);
            appointment.setUUIdDoctor(uuidMedico);
            appointment.setDate(fecha);
            appointment.setStartHour(hora);
            appointment.setReason(motivo);
            appointment.setStatus("programada");
            appointment.setObservation(observaciones);
            appointment.setDeleted(false);

            CreateAppointment createAppointment = new CreateAppointment();
            createAppointment.createAppointment(appointment);

            JOptionPane.showMessageDialog(this, "Cita creada correctamente.");

            txtInePaci.setText("");
            txtFecha.setText("");
            txtHora.setText("");
            txtmotivo.setText("");
            txtObservaciones.setText("");
            comboMedicos.setSelectedIndex(-1);
            txtUUIDcita.setText(UUID.randomUUID().toString());

        } catch (NumberFormatException exception) {
            JOptionPane.showMessageDialog(this, "El INE debe ser un número válido.");
        } catch (java.time.format.DateTimeParseException exception) {
            JOptionPane.showMessageDialog(this, "La fecha debe tener formato YYYY-MM-DD\ny la hora formato HH:mm.");
        } catch (Exception exception) {
            JOptionPane.showMessageDialog(this, "Error al crear la cita: " + exception.getMessage());
        }
    }//GEN-LAST:event_ButonCrrearCitaActionPerformed

