    private void eliminarbotonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarbotonActionPerformed
        // TODO add your handling code here:
        String textoIne = txtSearch.getText().trim();

        if (textoIne.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el INE del paciente que desea eliminar.");
            return;
        }

        try {
            int ine = Integer.parseInt(textoIne);

            int respuesta = JOptionPane.showConfirmDialog(
                    this,
                    "¿Está seguro que desea eliminar este paciente?",
                    "Confirmar eliminación",
                    JOptionPane.YES_NO_OPTION
            );

            if (respuesta != JOptionPane.YES_OPTION) {
                return;
            }

            DeletePatient eliminar = new DeletePatient();
            boolean resultado = eliminar.deletePatient(ine);

            if (resultado) {
                JOptionPane.showMessageDialog(this, "Paciente eliminado correctamente.");
                txtSearch.setText("");
                BotonTodosActionPerformed(null);
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró un paciente con ese INE o ya fue eliminado.");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El INE debe ser un número entero válido.");
        }
    }//GEN-LAST:event_eliminarbotonActionPerformed

