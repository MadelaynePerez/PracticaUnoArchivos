    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        // TODO add your handling code here:
        String buscar = txtSearch.getText().trim();

        if (buscar.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un INE, nombre o apellido para buscar.");
            return;
        }

        SearchPatient searchPatient = new SearchPatient();

        ArrayList<Patient> resultados = searchPatient.searchPatient(buscar);

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        for (Patient patient : resultados) {

            modelo.addRow(new Object[]{
                patient.getIne(),
                patient.getFullName(),
                patient.getBirthdate(),
                patient.getGender(),
                patient.getPhoneNumber(),
                patient.getEmail(),
                patient.getBloodType()
            });
        }

        if (resultados.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró ningún paciente.");
        }
    }//GEN-LAST:event_botonBuscarActionPerformed

