    private void jComboBoxEspecialidadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxEspecialidadActionPerformed
        // TODO add your handling code here:
        if (jComboBoxEspecialidad.getSelectedItem() == null) {
            return;
        }

        String especialidad = jComboBoxEspecialidad.getSelectedItem().toString();

        if (especialidad.equals("Todas")) {
            cargarTabla(new ListDoctors().listDoctors());
            return;
        }

        ArrayList<Doctor> resultados = new ArrayList<>();

        for (Doctor doctor : new ListDoctors().listDoctors()) {
            if (doctor.getSpecialty().equalsIgnoreCase(especialidad)) {
                resultados.add(doctor);
            }
        }

        cargarTabla(resultados);

    }//GEN-LAST:event_jComboBoxEspecialidadActionPerformed

    private void jButtonDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDesactivarActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un medico de la tabla.");
            return;
        }

        String id = jTable1.getValueAt(fila, 0).toString();

        ChangeStatusDoctor changeStatus = new ChangeStatusDoctor();

        if (changeStatus.changeStatus(id, false)) {

            JOptionPane.showMessageDialog(this,
                    "Medico desactivado correctamente.");

            cargarDoctores();

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se encontro el medico.");
        }
    }//GEN-LAST:event_jButtonDesactivarActionPerformed

    private void jButtonActivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActivarActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un medico de la tabla.");
            return;
        }

        String id = jTable1.getValueAt(fila, 0).toString();

        ChangeStatusDoctor changeStatus = new ChangeStatusDoctor();

        if (changeStatus.changeStatus(id, true)) {

            JOptionPane.showMessageDialog(this,
                    "Medico activado correctamente.");

            cargarDoctores();

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se encontro el medico.");
        }
    }//GEN-LAST:event_jButtonActivarActionPerformed

