    private void BotonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonBuscarActionPerformed
        // TODO add your handling code here:
        String buscar = txtSearch.getText().trim();

        if (buscar.isEmpty()) {
            cargarTabla(new ListDoctors().listDoctors());
            return;
        }

        SearchDoctor searchDoctor = new SearchDoctor();
        ArrayList<Doctor> resultados = searchDoctor.searchDoctor(buscar);

        cargarTabla(resultados);

        if (resultados.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se encontraron medicos.");
        }

    }//GEN-LAST:event_BotonBuscarActionPerformed

