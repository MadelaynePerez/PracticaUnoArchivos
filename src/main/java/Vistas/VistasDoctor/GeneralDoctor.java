    private void cargarDoctores() {

        ListDoctors listDoctors = new ListDoctors();

        ArrayList<Doctor> doctores = listDoctors.listDoctors();

        javax.swing.table.DefaultTableModel modelo
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0);

        for (Doctor doctor : doctores) {

            modelo.addRow(new Object[]{
                doctor.getId(),
                doctor.getFullName(),
                doctor.getSpecialty(),
                doctor.getPhoneNumber(),
                doctor.getEmail(),
                doctor.getStartHour(),
                doctor.getEndHour(),
                doctor.isActive() ? "Activo" : "Inactivo"
            });
        }
    }

    private void cargarTabla(ArrayList<Doctor> doctores) {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        for (Doctor doctor : doctores) {
            modelo.addRow(new Object[]{
                doctor.getId(),
                doctor.getFullName(),
                doctor.getSpecialty(),
                doctor.getPhoneNumber(),
                doctor.getEmail(),
                doctor.getStartHour(),
                doctor.getEndHour(),
                doctor.isActive() ? "Activo" : "Inactivo"
            });
        }
    }

    private void cargarEspecialidades() {
        jComboBoxEspecialidad.removeAllItems();
        jComboBoxEspecialidad.addItem("Todas");

        ArrayList<String> especialidades = new ArrayList<>();

        for (Doctor doctor : new ListDoctors().listDoctors()) {
            if (!especialidades.contains(doctor.getSpecialty())) {
                especialidades.add(doctor.getSpecialty());
                jComboBoxEspecialidad.addItem(doctor.getSpecialty());
            }
        }
    }

